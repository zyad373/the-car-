
import streamlit as st
import pandas as pd
import joblib

st.set_page_config(
    page_title="Car Price Predictor",
    page_icon="🚗",
    layout="centered"
)

@st.cache_resource
def load_model():
    return joblib.load("car_price_model.pkl")

model = load_model()

# Model features
makes = [
    "Acura", "Alfa Romeo", "Aston Martin", "Audi",
    "BMW", "Bentley", "Bugatti", "Buick",
    "Cadillac", "Chevrolet", "Chrysler", "Dodge",
    "FIAT", "Ferrari", "Ford", "GMC", "Genesis",
    "HUMMER", "Honda", "Hyundai", "Infiniti",
    "Kia", "Lamborghini", "Land Rover", "Lexus",
    "Lincoln", "Lotus", "Maserati", "Maybach",
    "Mazda", "McLaren", "Mercedes-Benz", "Mitsubishi",
    "Nissan", "Oldsmobile", "Plymouth", "Pontiac",
    "Porsche", "Rolls-Royce", "Saab", "Scion",
    "Spyker", "Subaru", "Suzuki", "Tesla",
    "Toyota", "Volkswagen", "Volvo"
]

st.title("🚗 Car Price Predictor")
st.write("Predict a car's estimated price using Machine Learning.")

st.divider()

st.subheader("Enter Car Information")

year = st.number_input(
    "Manufacturing Year",
    min_value=1900,
    max_value=2035,
    value=2020
)

hp = st.number_input(
    "Engine Horsepower",
    min_value=1,
    max_value=3000,
    value=200
)

make = st.selectbox("Car Manufacturer", makes)

size = st.selectbox(
    "Vehicle Size",
    ["Compact", "Large", "Midsize"]
)

transmission = st.selectbox(
    "Transmission Type",
    [
        "AUTOMATED_MANUAL",
        "AUTOMATIC",
        "DIRECT_DRIVE",
        "MANUAL",
        "UNKNOWN"
    ]
)

st.divider()

if st.button("Predict Price 🚀", use_container_width=True):

    # Start with all model features set to zero.
    features = {
        name: 0
        for name in model.feature_names_in_
    }

    features["year"] = year
    features["engine hp"] = hp

    features[f"make_{make}"] = 1
    features[f"vehicle size_{size}"] = 1
    features[f"transmission type_{transmission}"] = 1

    input_data = pd.DataFrame([features])

    prediction = model.predict(input_data)[0]

    st.success("Prediction completed!")

    st.metric(
        "Estimated Car Price",
        f"{prediction:,.2f}"
    )

    st.caption(
        "This is an estimated price generated by the ML model."
    )

st.divider()
st.caption("Powered by Python, Scikit-learn and Streamlit.")
